"""Generate the benchmark catalog from benchmark module metadata."""

from __future__ import annotations

import ast
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BENCHMARK_ROOT = ROOT / "benchmarks"


@dataclass(frozen=True)
class BenchmarkMetadata:
    """Static metadata extracted without importing or running a benchmark."""

    benchmark_id: str
    module_path: str
    expected_runtime_seconds: float
    description: str


def _assigned_literal(tree: ast.Module, name: str) -> object:
    for node in tree.body:
        targets: list[ast.expr] = []
        value_node: ast.expr | None = None
        if isinstance(node, ast.Assign):
            targets = node.targets
            value_node = node.value
        elif isinstance(node, ast.AnnAssign):
            targets = [node.target]
            value_node = node.value
        if any(isinstance(target, ast.Name) and target.id == name for target in targets):
            if value_node is None:
                raise ValueError(f"Benchmark metadata {name} cannot be empty")
            try:
                return ast.literal_eval(value_node)
            except (ValueError, TypeError) as exc:
                raise ValueError(f"{name} must be a literal in {tree}") from exc
    raise ValueError(f"Benchmark is missing required {name} metadata")


def discover_benchmarks(*, include_heldout: bool = False) -> tuple[BenchmarkMetadata, ...]:
    """Discover benchmark metadata in stable path order.

    Held-out rulers are excluded from the public catalog by default so they do
    not accidentally become contributor targets.
    """
    discovered: list[BenchmarkMetadata] = []
    for path in sorted(BENCHMARK_ROOT.rglob("*.py")):
        relative = path.relative_to(ROOT).as_posix()
        if path.name == "__init__.py" or (not include_heldout and "heldout/" in relative):
            continue
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=relative)
        benchmark_id = _assigned_literal(tree, "BENCHMARK_ID")
        budget = _assigned_literal(tree, "EXPECTED_RUNTIME_SECONDS")
        if not isinstance(benchmark_id, str) or not benchmark_id:
            raise ValueError(f"BENCHMARK_ID must be a non-empty string in {relative}")
        if isinstance(budget, bool) or not isinstance(budget, (int, float)) or budget <= 0:
            raise ValueError(f"EXPECTED_RUNTIME_SECONDS must be positive in {relative}")
        description = ast.get_docstring(tree, clean=True) or "No description provided."
        discovered.append(
            BenchmarkMetadata(
                benchmark_id=benchmark_id,
                module_path=relative,
                expected_runtime_seconds=float(budget),
                description=description.splitlines()[0],
            )
        )
    return tuple(sorted(discovered, key=lambda item: item.benchmark_id))


def _format_budget(seconds: float) -> str:
    return f"~{seconds:g}s"


def generate_catalog(*, include_heldout: bool = False) -> str:
    """Return the canonical benchmark catalog markdown."""
    benchmarks = discover_benchmarks(include_heldout=include_heldout)
    lines = [
        "# Benchmark Catalog",
        "",
        "> Generated by `tools/generate_benchmark_catalog.py`; do not edit manually.",
        "> Public catalog entries are deterministic contributor-facing rulers.",
        "",
        "| Benchmark ID | Module | Runtime budget | Description |",
        "| --- | --- | ---: | --- |",
    ]
    for benchmark in benchmarks:
        lines.append(
            f"| `{benchmark.benchmark_id}` | `{benchmark.module_path}` | "
            f"{_format_budget(benchmark.expected_runtime_seconds)} | {benchmark.description} |"
        )
    lines.extend(
        [
            "",
            "## Running a benchmark",
            "",
            "```bash",
            "python tools/run_bench.py benchmarks/tank/survival_5k.py --seed 42",
            "```",
            "",
            "Runtime budgets are diagnostic references, not timeouts or scoring inputs.",
            "Held-out benchmarks are intentionally omitted; use them only through their",
            "explicit evaluation workflows.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    output_path = ROOT / "docs" / "BENCHMARK_CATALOG.md"
    output_path.write_text(generate_catalog(), encoding="utf-8")
    print(f"Benchmark catalog generated at: {output_path}")


if __name__ == "__main__":
    main()
